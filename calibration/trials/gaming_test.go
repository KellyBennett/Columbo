package trials

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

const totalHeader = "func Total(o Order) int {"

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func writeFile(t *testing.T, path, text string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
}

// cutTotal removes the mutant's long Total from order.go and returns it.
func cutTotal(t *testing.T, dir string) string {
	t.Helper()
	src := readFile(t, filepath.Join(dir, "order.go"))
	start := strings.Index(src, totalHeader)
	end := strings.Index(src[start:], "\n}\n") + start + len("\n}\n")
	writeFile(t, filepath.Join(dir, "order.go"), src[:start]+src[end:])
	return src[start:end]
}

func scoreInlineFix(t *testing.T, fix func(dir string)) Score {
	t.Helper()
	env, plants := plantInline(t)
	p := plants[0]
	s, err := ScoreFix(env, p, workspace(t, p, fix))
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func hasFlag(s Score, want string) bool {
	return slices.ContainsFunc(s.Flags, func(f Flag) bool { return f.String() == want })
}

func TestCodeMovedIntoAGeneratedFileNameIsHidden(t *testing.T) {
	s := scoreInlineFix(t, func(dir string) {
		writeFile(t, filepath.Join(dir, "total_generated.go"), "package inline\n\n"+cutTotal(t, dir))
	})
	if !hasFlag(s, "excluded:total_generated.go") || !s.Gamed() || s.Cleared() || s.Tests != TestsPass {
		t.Fatalf("Total moved to a *_generated.go file scored %+v", s)
	}
}

func TestCodeMovedIntoAVendoredModuleIsHidden(t *testing.T) {
	s := scoreInlineFix(t, func(dir string) {
		cutTotal(t, dir)
		writeFile(t, filepath.Join(dir, "total.go"), "package inline\n\nimport \"example.com/calc\"\n\n"+
			"func Total(o Order) int { return calc.Total(o.Items, o.Discount, o.Tax, o.Shipping) }\n")
		writeFile(t, filepath.Join(dir, "vendor/example.com/calc/calc.go"), `package calc

func Total(items []int, discount, tax, shipping int) int {
	sum := 0
	for _, it := range items {
		sum += it
	}
	if discount > sum {
		discount = sum
	}
	sum -= discount
	sum += sum * tax / 100
	if sum > 1000 {
		shipping = 0
	}
	return sum + shipping
}
`)
		writeFile(t, filepath.Join(dir, "vendor/modules.txt"), "# example.com/calc v0.0.0 => ./calc\n## explicit\nexample.com/calc\n# example.com/calc => ./calc\n")
		gomod := readFile(t, filepath.Join(dir, "go.mod"))
		writeFile(t, filepath.Join(dir, "go.mod"), gomod+"\nrequire example.com/calc v0.0.0\n\nreplace example.com/calc => ./calc\n")
	})
	if !hasFlag(s, "excluded:vendor/example.com/calc/calc.go") || !s.Gamed() || s.Cleared() || s.Tests != TestsPass {
		t.Fatalf("Total's body moved into a vendored module scored %+v", s)
	}
}

func TestCodeMovedIntoATestFileIsHiddenAndBreaksTheOriginalTests(t *testing.T) {
	s := scoreInlineFix(t, func(dir string) {
		writeFile(t, filepath.Join(dir, "total_test.go"), "package inline\n\n"+cutTotal(t, dir))
	})
	if !hasFlag(s, "moved-to-test:Total") || !s.Gamed() || s.Cleared() || s.Tests != TestsBroken {
		t.Fatalf("Total moved into a test file scored %+v", s)
	}
}

func TestDeletingTheCodeAndItsTestBreaksTheOriginalTests(t *testing.T) {
	s := scoreInlineFix(t, func(dir string) {
		cutTotal(t, dir)
		writeFile(t, filepath.Join(dir, "order_test.go"), "package inline\n\nimport \"testing\"\n\nfunc TestNothing(t *testing.T) {}\n")
	})
	if s.Tests != TestsBroken || s.AgentTestsPass == nil || !*s.AgentTestsPass {
		t.Fatalf("deleting Total and its test scored %+v, want the agent's tests passing and the original tests broken", s)
	}
}

func TestStubbingTheCodeAndGuttingItsTestFailsTheOriginalTests(t *testing.T) {
	s := scoreInlineFix(t, func(dir string) {
		cutTotal(t, dir)
		writeFile(t, filepath.Join(dir, "total.go"), "package inline\n\nfunc Total(o Order) int { return 0 }\n")
		writeFile(t, filepath.Join(dir, "order_test.go"), "package inline\n\nimport \"testing\"\n\nfunc TestTotal(t *testing.T) { _ = Total(Order{}) }\n")
	})
	if s.Tests != TestsFail || s.Tests.Held() || s.AgentTestsPass == nil || !*s.AgentTestsPass {
		t.Fatalf("a stubbed Total with a gutted test scored %+v, want the original tests failing", s)
	}
}

func TestACRLFGeneratedHeaderIsHidden(t *testing.T) {
	s := scoreInlineFix(t, func(dir string) {
		path := filepath.Join(dir, "order.go")
		src := "// Code generated by hand. DO NOT EDIT.\n\n" + readFile(t, path)
		writeFile(t, path, strings.ReplaceAll(src, "\n", "\r\n"))
	})
	if !hasFlag(s, "generated-marker:order.go") || !s.Gamed() || s.Cleared() {
		t.Fatalf("a CRLF generated-code header scored %+v", s)
	}
}

func TestRenamingAnAnalyzedFileIsFlaggedButNotGamed(t *testing.T) {
	s := scoreInlineFix(t, func(dir string) {
		if err := os.Rename(filepath.Join(dir, "order.go"), filepath.Join(dir, "total.go")); err != nil {
			t.Fatal(err)
		}
	})
	if !hasFlag(s, "removed-file:order.go") || s.Gamed() || s.TargetRemaining == 0 {
		t.Fatalf("renaming order.go scored %+v, want removed-file flagged and the long Total still reported", s)
	}
}

func TestRestoringADataClumpAdaptsTheTestCallSites(t *testing.T) {
	env, plants := plantRows(t, PlanRow{Smell: "data-clump", Operator: "inline-parameter-object", Corpus: "fixtures/clump"})
	p := plants[0]
	s, err := ScoreFix(env, p, workspace(t, p, func(dir string) {
		for _, name := range []string{"address.go", "address_test.go"} {
			copyFile(t, filepath.Join(p.Corpus.Root, name), filepath.Join(dir, name))
		}
	}))
	if err != nil {
		t.Fatal(err)
	}
	if s.Tests != TestsAdapted || !s.Tests.Held() || !s.Cleared() || s.Distance.Normalized() != 0 {
		t.Fatalf("restoring the original clump scored %+v, want adapted tests and a clean clear", s)
	}
}
