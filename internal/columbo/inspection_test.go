const inspectionFixture = `package fixture
type Cell struct { Value int }
type Alias = Cell
func (c *Cell) Put(v int) { c.Value=v }
func (c Alias) Read() int { return c.Value }
type Box[T any] struct { Value T }
func (b *Box[T]) Read() T { return b.Value }
type Embedded struct { held *Cell }
type Owner struct { *Embedded; local Cell; dynamic interface { Put(int) }; mapping map[string]int }
func (o *Owner) Update(handle *Cell) { o.held.Put(1); alias:=handle; alias.Put(2); o.dynamic.Put(3); o.local.Put(4); (*Cell).Put(handle,5) }
func (o *Owner) Short() {}
func Free() {}
`

func inspectionTestModule(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	for name, data := range map[string]string{
		"go.mod":              "module fixture\n\ngo 1.25.1\n",
		"model.go":            inspectionFixture,
		"generated.go":        "// Code generated by fixture. DO NOT EDIT.\npackage fixture\nfunc (o *Owner) Generated() {}\n",
		"platform_windows.go": "package fixture\nfunc (o *Owner) PlatformOnly() {}\n",
		"model_test.go":       "package fixture\nfunc (o *Owner) TestOnly() {}\n",
	} {
		require.NoError(t, os.WriteFile(filepath.Join(root, name), []byte(data), 0600))
	}
	return root
}
func inspectTestFacts(t *testing.T, root string) inspectionFacts {
	t.Helper()
	var buffer bytes.Buffer
	require.NoError(t, WriteInspectionFacts(root, "", nil, &buffer))
	var facts inspectionFacts
	require.NoError(t, json.Unmarshal(buffer.Bytes(), &facts))
	return facts
}
func TestInspectionCompleteRuntimeMethodsAndCallBounds(t *testing.T) {
	root := inspectionTestModule(t)
	facts := inspectTestFacts(t, root)
	methods := map[string]inspectionDeclaration{}
	for _, d := range facts.Declarations {
		methods[d.Symbol] = d
	}
	require.Equal(t, "fixture.Cell", methods["fixture.(Cell).Read"].ReceiverKey)
	require.Equal(t, "fixture.Box", methods["fixture.(*Box).Read"].ReceiverKey)
	require.Contains(t, methods, "fixture.(*Owner).Generated")
	require.NotContains(t, methods, "fixture.(*Owner).PlatformOnly")
	require.NotContains(t, methods, "fixture.(*Owner).TestOnly")
	calls := methods["fixture.(*Owner).Update"].Calls
	require.Len(t, calls, 5)
	require.NotNil(t, calls[0].Target)
	require.NotNil(t, calls[1].Binding)
	require.Nil(t, calls[2].Target)
	require.NotNil(t, calls[3].Target)
	require.NotNil(t, calls[4].Target)
	require.Equal(t, "method-expression", calls[4].ReceiverForm)
	for _, call := range calls {
		if call.Target != nil {
			require.Empty(t, call.Target.Calls)
		}
	}
	selected, generated := 0, 0
	for _, f := range facts.Files {
		if f.Selected {
			selected++
		}
		if f.Generated {
			generated++
			require.True(t, f.Selected)
			require.False(t, f.Target)
		}
	}
	require.Equal(t, 2, selected)
	require.Equal(t, 1, generated)
}
func TestInspectionSourceRangesAndAnalysisUnchanged(t *testing.T) {
	root := inspectionTestModule(t)
	before, err := Analyze(root, []string{"./..."}, Defaults())
	require.NoError(t, err)
	facts := inspectTestFacts(t, root)
	for _, d := range facts.Declarations {
		data, err := os.ReadFile(filepath.Join(root, d.Path))
		require.NoError(t, err)
		require.Equal(t, inspectionHash(data), d.FileSHA)
		require.Equal(t, inspectionHash(data[d.StartOffset:d.EndOffset]), d.SHA)
	}
	after, err := Analyze(root, []string{"./..."}, Defaults())
	require.NoError(t, err)
	require.Equal(t, canonical(before), canonical(after))
	require.Len(t, facts.Files, 4)
}
func TestInspectionRejectsSymlinksAndTypeErrors(t *testing.T) {
	root := inspectionTestModule(t)
	link := filepath.Join(t.TempDir(), "linked")
	require.NoError(t, os.Symlink(root, link))
	require.Error(t, WriteInspectionFacts(link, "", nil, &bytes.Buffer{}))
	require.NoError(t, os.WriteFile(filepath.Join(root, "invalid.go"), []byte("package fixture\nfunc Broken(){ missing() }\n"), 0600))
	require.Error(t, WriteInspectionFacts(root, "", nil, &bytes.Buffer{}))
}
